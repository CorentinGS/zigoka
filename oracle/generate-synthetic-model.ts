import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { GoModelRuntime } from "../vendor/moka/src/runtime.ts";
import { compareFiles } from "./fixture-files.ts";
import { createMulberry32 } from "./mulberry32.ts";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootDirectory = path.resolve(scriptDirectory, "..", "..");
const sourceDirectory = path.join(rootDirectory, "vendor", "moka", "model");
const outputDirectory = path.join(rootDirectory, "models", "synthetic-19");

const SEED = 19;
const BOARD_SIZE = 19;
const AREA = BOARD_SIZE * BOARD_SIZE;
const SOURCE_AREA = 81;
const POLICY_SCALE_FACTOR = 1;
const VALUE_SCALE_FACTOR = 1;
const BLOCK_ALIGNMENT = 4;
const MODEL_FILES = ["go-model.json", "go-model.bin"];

const POLICY_WEIGHT = "policy.linear.weight";
const POLICY_BIAS = "policy.linear.bias";
const VALUE_HIDDEN_WEIGHT = "value.hidden.weight";
const GENERATED_TENSORS = [POLICY_WEIGHT, POLICY_BIAS, VALUE_HIDDEN_WEIGHT];
const COPIED_TENSOR_PATTERN =
  /^(stem|residual\.\d+\.[a-z.]+|policy\.convolution|value\.convolution|value\.output)\.(weight|bias)$|^value\.hidden\.bias$/;

type ManifestTensor = {
  dataOffset: number;
  dtype: string;
  scaleOffset?: number;
  shape: number[];
};

type Manifest = {
  architecture: { boardSize: number; policyMoveCount: number; policyChannelCount: number };
  sha256: string;
  tensors: Record<string, ManifestTensor>;
  weightsBytes: number;
};

type Block = {
  tensorName: string;
  field: "dataOffset" | "scaleOffset";
  sourceOffset: number;
  bytes: Uint8Array;
};

function fail(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

const elementBytes = (dtype: string): number => {
  switch (dtype) {
    case "int8":
      return 1;
    case "int16":
      return 2;
    case "float32":
      return 4;
    default:
      return fail(`Unsupported dtype ${dtype}.`);
  }
};

const getElementCount = (shape: number[]) => shape.reduce((product, size) => product * size, 1);

const readSource = () => {
  const manifest = JSON.parse(
    fs.readFileSync(path.join(sourceDirectory, "go-model.json"), "utf8"),
  ) as Manifest;
  const weights = new Uint8Array(fs.readFileSync(path.join(sourceDirectory, "go-model.bin")));

  for (const name of Object.keys(manifest.tensors)) {
    if (!GENERATED_TENSORS.includes(name) && !COPIED_TENSOR_PATTERN.test(name)) {
      fail(`Tensor ${name} of moka-9 is neither copied nor generated by the recipe.`);
    }
  }

  if (manifest.architecture.boardSize * manifest.architecture.boardSize !== SOURCE_AREA) {
    fail(`The source model must be 9×9, found boardSize ${manifest.architecture.boardSize}.`);
  }

  return { manifest, weights };
};

const sliceTensor = (weights: Uint8Array, tensor: ManifestTensor) =>
  weights.subarray(
    tensor.dataOffset,
    tensor.dataOffset + getElementCount(tensor.shape) * elementBytes(tensor.dtype),
  );

const sliceScales = (weights: Uint8Array, tensor: ManifestTensor) =>
  new Float32Array(
    weights.slice(tensor.scaleOffset!, tensor.scaleOffset! + (tensor.shape[0] as number) * 4).buffer,
  );

const resampleRows = (
  source: Int8Array,
  sourceColumnCount: number,
  sourceRows: number[],
  columnCount: number,
  pick: (count: number) => number,
): Int8Array => {
  const values = new Int8Array(sourceRows.length * columnCount);

  for (let row = 0; row < sourceRows.length; row += 1) {
    const sourceOffset = (sourceRows[row] as number) * sourceColumnCount;

    for (let column = 0; column < columnCount; column += 1) {
      values[row * columnCount + column] = source[sourceOffset + pick(sourceColumnCount)] as number;
    }
  }

  return values;
};

const generateHeads = (manifest: Manifest, weights: Uint8Array) => {
  const random = createMulberry32(SEED);
  const pick = (count: number) => Math.floor(random() * count);
  const policyWeight = manifest.tensors[POLICY_WEIGHT] as ManifestTensor;
  const policyBias = manifest.tensors[POLICY_BIAS] as ManifestTensor;
  const valueWeight = manifest.tensors[VALUE_HIDDEN_WEIGHT] as ManifestTensor;
  const policyColumns = policyWeight.shape[1] as number;
  const valueColumns = valueWeight.shape[1] as number;
  const policyChannels = policyColumns / SOURCE_AREA;
  const valueChannels = valueColumns / SOURCE_AREA;
  const newPolicyColumns = policyChannels * AREA;
  const newValueColumns = valueChannels * AREA;

  const sourcePolicyValues = new Int8Array(sliceTensor(weights, policyWeight).slice().buffer);
  const sourcePolicyScales = sliceScales(weights, policyWeight);
  const sourcePolicyBias = new Float32Array(sliceTensor(weights, policyBias).slice().buffer);
  const policyRows: number[] = [];
  const policyValues = new Int8Array((AREA + 1) * newPolicyColumns);

  for (let row = 0; row <= AREA; row += 1) {
    const sourceRow = row === AREA ? SOURCE_AREA : pick(SOURCE_AREA);
    policyRows.push(sourceRow);
    policyValues.set(
      resampleRows(sourcePolicyValues, policyColumns, [sourceRow], newPolicyColumns, pick),
      row * newPolicyColumns,
    );
  }

  const policyScaleRatio = Math.sqrt(policyColumns / newPolicyColumns) * POLICY_SCALE_FACTOR;
  const policyScales = Float32Array.from(policyRows, (sourceRow) =>
    Math.fround((sourcePolicyScales[sourceRow] as number) * policyScaleRatio),
  );
  const policyBiasValues = Float32Array.from(
    policyRows,
    (sourceRow) => sourcePolicyBias[sourceRow] as number,
  );

  const valueRowCount = valueWeight.shape[0] as number;
  const sourceValueValues = new Int8Array(sliceTensor(weights, valueWeight).slice().buffer);
  const sourceValueScales = sliceScales(weights, valueWeight);
  const valueRows = Array.from({ length: valueRowCount }, (_, row) => row);
  const valueValues = resampleRows(sourceValueValues, valueColumns, valueRows, newValueColumns, pick);
  const valueScaleRatio = Math.sqrt(valueColumns / newValueColumns) * VALUE_SCALE_FACTOR;
  const valueScales = Float32Array.from(valueRows, (row) =>
    Math.fround((sourceValueScales[row] as number) * valueScaleRatio),
  );

  return {
    shapes: {
      [POLICY_WEIGHT]: [AREA + 1, newPolicyColumns],
      [POLICY_BIAS]: [AREA + 1],
      [VALUE_HIDDEN_WEIGHT]: [valueRowCount, newValueColumns],
    } as Record<string, number[]>,
    data: {
      [POLICY_WEIGHT]: new Uint8Array(policyValues.buffer),
      [POLICY_BIAS]: new Uint8Array(policyBiasValues.buffer),
      [VALUE_HIDDEN_WEIGHT]: new Uint8Array(valueValues.buffer),
    } as Record<string, Uint8Array>,
    scales: {
      [POLICY_WEIGHT]: new Uint8Array(policyScales.buffer),
      [VALUE_HIDDEN_WEIGHT]: new Uint8Array(valueScales.buffer),
    } as Record<string, Uint8Array>,
  };
};

const collectBlocks = (manifest: Manifest, weights: Uint8Array): Block[] => {
  const heads = generateHeads(manifest, weights);
  const blocks: Block[] = [];

  for (const [tensorName, tensor] of Object.entries(manifest.tensors)) {
    blocks.push({
      tensorName,
      field: "dataOffset",
      sourceOffset: tensor.dataOffset,
      bytes: heads.data[tensorName] ?? sliceTensor(weights, tensor),
    });

    if (tensor.scaleOffset !== undefined) {
      blocks.push({
        tensorName,
        field: "scaleOffset",
        sourceOffset: tensor.scaleOffset,
        bytes:
          heads.scales[tensorName] ??
          weights.subarray(tensor.scaleOffset, tensor.scaleOffset + (tensor.shape[0] as number) * 4),
      });
    }
  }

  for (const [tensorName, shape] of Object.entries(heads.shapes)) {
    (manifest.tensors[tensorName] as ManifestTensor).shape = shape;
  }

  return blocks.sort((left, right) => left.sourceOffset - right.sourceOffset);
};

const buildModel = () => {
  const { manifest, weights } = readSource();
  const blocks = collectBlocks(manifest, weights);
  const chunks: Uint8Array[] = [];
  let offset = 0;

  for (const block of blocks) {
    const padding = (BLOCK_ALIGNMENT - (offset % BLOCK_ALIGNMENT)) % BLOCK_ALIGNMENT;

    if (padding > 0) {
      chunks.push(new Uint8Array(padding));
      offset += padding;
    }

    (manifest.tensors[block.tensorName] as ManifestTensor)[block.field] = offset;
    chunks.push(block.bytes);
    offset += block.bytes.length;
  }

  const bin = Buffer.concat(chunks);

  manifest.architecture.boardSize = BOARD_SIZE;
  manifest.architecture.policyMoveCount = AREA + 1;
  manifest.weightsBytes = bin.length;
  manifest.sha256 = crypto.createHash("sha256").update(bin).digest("hex");

  return {
    manifest,
    files: new Map<string, Buffer>([
      ["go-model.json", Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`, "utf8")],
      ["go-model.bin", bin],
    ]),
  };
};

const assertLoadable = (manifest: Manifest, bin: Buffer): void => {
  const weightsBuffer = bin.buffer.slice(bin.byteOffset, bin.byteOffset + bin.byteLength);
  let result;

  try {
    const runtime = GoModelRuntime.create(
      manifest as unknown as GoModelManifest,
      weightsBuffer as ArrayBuffer,
    );
    result = runtime.infer(new Float32Array(AREA * 12));
  } catch (error) {
    fail(
      `Moka cannot run the generated model: ${error instanceof Error ? error.message : error}`,
    );
  }

  if (!result.policyLogits.every(Number.isFinite) || !Number.isFinite(result.value)) {
    fail("The generated model gives a non-finite output on a zero input.");
  }
};

const writeFiles = (directory: string, files: Map<string, Buffer>): void => {
  fs.mkdirSync(directory, { recursive: true });

  for (const [name, content] of files) {
    fs.writeFileSync(path.join(directory, name), content);
  }
};

const main = (): void => {
  const shouldCheck = process.argv.includes("--check");
  const { manifest, files } = buildModel();

  assertLoadable(manifest, files.get("go-model.bin") as Buffer);

  if (!shouldCheck) {
    writeFiles(outputDirectory, files);
    process.stdout.write(
      `Wrote models/synthetic-19 (${manifest.weightsBytes} bytes, sha256 ${manifest.sha256}).\n`,
    );

    return;
  }

  if (!fs.existsSync(path.join(outputDirectory, "go-model.json"))) {
    fail('models/synthetic-19 is missing. Run "pnpm models" first.');
  }

  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "synthetic-19-"));
  writeFiles(temporaryDirectory, files);
  const difference = compareFiles(outputDirectory, temporaryDirectory, MODEL_FILES);
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });

  if (difference) {
    fail(`models/synthetic-19 is not reproducible: ${difference}.`);
  }

  process.stdout.write("models/synthetic-19 is reproducible, byte for byte.\n");
};

main();
